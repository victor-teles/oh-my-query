import { describe, expect, it, vi } from "vitest";

import type { ClipboardSource } from "./clipboard-offer.ts";

import { createClipboardOffer } from "./clipboard-offer.ts";
import { summonPayload } from "./summon-payload.ts";

const UUID = "3f2a1b4c-9d8e-4f7a-b6c5-d4e3f2a1c91e";
const PLAIN = ["public.utf8-plain-text", "NSStringPboardType"];

const source = (overrides: Partial<ClipboardSource> = {}) => {
  const readText = vi.fn<ClipboardSource["readText"]>(() => UUID);
  return {
    enabled: () => true,
    formats: () => PLAIN,
    readText,
    ...overrides,
  };
};

describe("createClipboardOffer", () => {
  it("offers a classified id from the clipboard", () => {
    expect(createClipboardOffer(source())()).toStrictEqual({
      kind: "uuid",
      value: UUID,
    });
  });

  it.each([
    ["the setting is off", { enabled: () => false }],
    [
      "the item is concealed",
      { formats: () => [...PLAIN, "org.nspasteboard.ConcealedType"] },
    ],
    [
      "the item is transient",
      { formats: () => ["org.nspasteboard.TransientType"] },
    ],
    [
      "the item was generated",
      { formats: () => [...PLAIN, "org.nspasteboard.AutoGeneratedType"] },
    ],
    ["the pasteboard types are unknown", { formats: () => null }],
  ])("never reads when %s", (_label, overrides) => {
    const clipboard = source(overrides);
    expect(createClipboardOffer(clipboard)()).toBeNull();
    expect(clipboard.readText).not.toHaveBeenCalled();
  });

  it.each([
    ["prose", "remember to call Ada"],
    ["an empty clipboard", null],
    ["a long text that starts with an id", `${UUID} ${"x".repeat(400)}`],
  ])("offers nothing for %s", (_label, text) => {
    expect(createClipboardOffer(source({ readText: () => text }))()).toBeNull();
  });

  it("classifies only the first 320 characters", () => {
    const padded = `${" ".repeat(300)}42${" ".repeat(100)}`;
    expect(
      createClipboardOffer(source({ readText: () => padded }))()
    ).toStrictEqual({ kind: "integer", value: "42" });
  });
});

describe("summonPayload", () => {
  it("passes the offer through", () => {
    expect(
      summonPayload(() => ({ kind: "integer", value: "42" }))
    ).toStrictEqual({ clipboard: { kind: "integer", value: "42" } });
  });

  it("still shows the launcher when reading the clipboard throws", () => {
    const error = vi.spyOn(console, "error").mockReturnValue();
    expect(
      summonPayload(() => {
        throw new Error("pasteboard busy");
      })
    ).toStrictEqual({ clipboard: null });
    expect(error).toHaveBeenCalledOnce();
    error.mockRestore();
  });
});
